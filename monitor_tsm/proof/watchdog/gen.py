"""Claude 05/11/2026: build the watchdog k-induction harness (SymbiYosys) for rtl/top/m_tsmx_engine.sv.

Every submodule instantiated by the engine is replaced by a stub whose outputs are unconstrained each cycle
((* anyseq *)): the proof then holds for ANY behaviour of ingress, splice, cert, selector, supervisor, arbiter,
recorder, health, hash, math, both sweeps and the CSR block (incl. arbitrary CSR resets). The engine itself is copied
unmodified except for an `ifdef FORMAL` property block appended before `endmodule`. Nothing under rtl/ is edited.
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
RTL = HERE.parents[1] / "rtl"
SUBS = {"m_tsmx_ingress": "ingress/m_tsmx_ingress.sv", "m_tsmx_splice": "splice/m_tsmx_splice.sv",
        "m_tsmx_cert": "cert/m_tsmx_cert.sv", "m_tsmx_sel": "sel/m_tsmx_sel.sv",
        "m_tsmx_supervisor": "supervisor/m_tsmx_supervisor.sv", "m_tsmx_arb": "arb/m_tsmx_arb.sv",
        "m_tsmx_rec": "rec/m_tsmx_rec.sv", "m_tsmx_health_lane": "health/m_tsmx_health_lane.sv",
        "m_tsmx_hash": "top/m_tsmx_hash.sv", "m_tsmx_math": "top/m_tsmx_math.sv",
        "m_tsmx_sweep": "top/m_tsmx_sweep.sv", "m_tsmx_csr": "csr/m_tsmx_csr.sv"}

stubs = ["// generated by gen.py: unconstrained stubs (outputs anyseq)\n"]
for mod, rel in SUBS.items():
    src = (RTL / rel).read_text(encoding="utf-8")
    m = re.search(r"^module\s+" + mod + r"\b.*?^\);", src, re.S | re.M)
    assert m, mod
    header = m.group(0)
    header = re.sub(r"//[^\n]*", "", header)
    outs = re.findall(r"output\s+(?:logic|wire|reg)?\s*(\[[^\]]+\])?\s*(\w+)", header)
    body = []
    for width, name in outs:
        body.append(f"  (* anyseq *) logic {width or ''} fv_{name};\n  assign {name} = fv_{name};\n")
    stubs.append(header + "\n" + "".join(body) + "endmodule\n\n")
(HERE / "stubs.sv").write_text("".join(stubs), encoding="utf-8")

eng = (RTL / "top/m_tsmx_engine.sv").read_text(encoding="utf-8")
props = (HERE / "props.svh").read_text(encoding="utf-8")
# Yosys cannot parse the unpacked localparam ROMs of f_mod20k (CLAUDE-FIX-004). Its documented result is v % 20000
# (only the 20 ms tick uses it; no watchdog property depends on it): substitute the plain modulo in the FV copy.
eng = re.sub(r"  localparam logic \[9:0\] LPARA_MOD_[ABC] \[0:511\] = '\{[^}]*\};\n", "", eng)
a = eng.index("  function automatic logic [31:0] f_mod20k")
b = eng.index("endfunction", a) + len("endfunction")
eng = eng[:a] + "  function automatic logic [31:0] f_mod20k(input logic [31:0] w_v);\n    f_mod20k = w_v % 32'd20000;\n  endfunction" + eng[b:]
i = eng.rindex("endmodule")
(HERE / "engine_fv.sv").write_text(eng[:i] + props + "\n" + eng[i:], encoding="utf-8")
print("stubs:", len(SUBS), "engine_fv.sv written")
