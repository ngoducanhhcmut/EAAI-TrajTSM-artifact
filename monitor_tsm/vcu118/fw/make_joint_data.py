"""Claude 10/11/2026: DDR images for the VCU118 joint run (Traj planner -> firmware -> TSM-X), built from the
same files the RTL end-to-end bench uses (journalQ1/tsmx_hw/e2e_traj_tsm + tb/e2e/vec), so a board pass is
directly comparable with E2E_PASS frames=35 jobs=207.

Outputs in vcu118/fw/joint_data/:
  ddr_load.tsv   file <TAB> physical DDR address <TAB> bytes   (xsdb loads at 0x8000_0000 + address)
  planner_*.bin  planner weights/params at the planning_pkg addresses (16-byte AXI beats, little endian)
  wm_bank.bin    35 x 16 KiB world models (frame n at +n*0x4000), copied to WM_A 0x0064_0000 by firmware
  tsm_req.bin    207 x 5600 B: TSM-X request frame bytes (5585 B payload, MSB-first, zero padded)
  tsm_meta.bin   207 x 32 B: u32 frame_map, rsp_lo, rsp_hi, cmd_crc32, reset, ack_flag, now_us, pad
  wp_golden.bin  35 x 8 u32 recorded planner waypoints (RTL, bit exact)
  joint_layout.h addresses/counts for the firmware
"""
import zlib, struct, pathlib, sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[3]                        # vla_new_arch
E2E = ROOT / 'journalQ1' / 'tsmx_hw' / 'e2e_traj_tsm'
VEC = ROOT / 'tb' / 'e2e' / 'vec'
OUT = HERE / 'joint_data'
OUT.mkdir(exist_ok=True)

VW, REQW, RSPW, CMDW, INGW, SUPW, LOSTW, EVW = 48037, 44673, 38, 1897, 332, 8, 32, 1056
REQ_SHIFT = RSPW + CMDW + INGW + SUPW + LOSTW + EVW          # 3363
assert 1 + REQW + REQ_SHIFT == VW

REGIONS = [  # file, base, words (128-bit) -- e2e_planner_driver.sv ddr_rd()
    ('ddr_bert_weights.hex', 0x00000000, 393216), ('ddr_pos_emb.hex', 0x00600000, 8192),
    ('ddr_gru_bias.hex', 0x017D2000, 512), ('ddr_gru_weights.hex', 0x017D4000, 49152),
    ('ddr_gru_wout_staging.hex', 0x01894000, 512), ('ddr_gru_scale_zp.hex', 0x018A0000, 384),
    ('ddr_gru_wp_proj.hex', 0x018A8000, 384), ('ddr_param_a.hex', 0x01900000, 4096),
    ('ddr_param_b.hex', 0x01910000, 8192), ('ddr_param_c.hex', 0x01930000, 2048)]
WM_BANK, TSM_REQ, TSM_META, WP_GOLD = 0x10000000, 0x11000000, 0x11200000, 0x11210000
REQ_STRIDE, META_STRIDE, WM_STRIDE = 5600, 32, 0x4000


def hex_words(path, n):
    """$readmemh semantics: sequential words, '//' comments and '@addr' are not used in these files."""
    words = []
    for line in path.read_text().split('\n'):
        line = line.split('//')[0].strip()
        if not line:
            continue
        if line.startswith('@'):
            sys.exit(f'unexpected address directive in {path}')
        words.extend(int(t, 16) for t in line.split())
    if len(words) > n:
        sys.exit(f'{path}: {len(words)} words > {n}')
    if len(words) < n: print(f'note: {path.name} has {len(words)} of {n} words (rest zero)')
    return words + [0] * (n - len(words))


def beats(words):
    return b''.join(w.to_bytes(16, 'little') for w in words)


tsv = ['# file\tphys_addr\tbytes   (MicroBlaze/xsdb address = 0x80000000 + phys_addr)']
for name, base, n in REGIONS:
    data = beats(hex_words(VEC / name, n))
    fn = 'planner_' + name.replace('ddr_', '').replace('.hex', '.bin')
    (OUT / fn).write_bytes(data)
    tsv.append(f'{fn}\t0x{base:08X}\t{len(data)}')

wm = b''
for f in range(35):
    d = beats(hex_words(VEC / f's{f:02d}_wm.hex', 1024))
    assert len(d) == WM_STRIDE
    wm += d
(OUT / 'wm_bank.bin').write_bytes(wm)
tsv.append(f'wm_bank.bin\t0x{WM_BANK:08X}\t{len(wm)}')

vec = [int(l, 16) for l in (E2E / 'vectors.mem').read_text().split()]
fmap = [int(l, 16) for l in (E2E / 'frames.mem').read_text().split()]
rwp = [int(l, 16) for l in (E2E / 'recorded_wp.mem').read_text().split()]
assert len(vec) == len(fmap) == 207 and len(rwp) == 280
req_bin, meta_bin = b'', b''
for j, v in enumerate(vec):
    reset = v >> (VW - 1)
    req = (v >> REQ_SHIFT) & ((1 << REQW) - 1)
    rsp = (v >> (REQ_SHIFT - RSPW)) & ((1 << RSPW) - 1)
    cmd = (v >> (REQ_SHIFT - RSPW - CMDW)) & ((1 << CMDW) - 1)
    rb = (req << 7).to_bytes(5585, 'big')               # frame payload: 44673 bits + 7 zero bits
    req_bin += rb + bytes(REQ_STRIDE - 5585)
    cb = (cmd << 7).to_bytes(238, 'big')                 # command payload as received (txbuf[1903:0])
    now = (req >> 44641) & 0xFFFFFFFF
    ack = (req >> 33856) & 1
    meta_bin += struct.pack('<8I', fmap[j], rsp & 0xFFFFFFFF, rsp >> 32, zlib.crc32(cb) & 0xFFFFFFFF,
                            reset, ack, now, 0)
(OUT / 'tsm_req.bin').write_bytes(req_bin)
(OUT / 'tsm_meta.bin').write_bytes(meta_bin)
(OUT / 'wp_golden.bin').write_bytes(struct.pack('<280I', *rwp))
tsv += [f'tsm_req.bin\t0x{TSM_REQ:08X}\t{len(req_bin)}', f'tsm_meta.bin\t0x{TSM_META:08X}\t{len(meta_bin)}',
        f'wp_golden.bin\t0x{WP_GOLD:08X}\t{len(rwp) * 4}']
(OUT / 'ddr_load.tsv').write_text('\n'.join(tsv) + '\n', newline='\n')
(OUT / 'joint_layout.h').write_text(f"""/* generated by make_joint_data.py (Claude 10/11/2026) */
#define DDR_MB_BASE   0x80000000u
#define WM_BANK_PHYS  0x{WM_BANK:08X}u
#define TSM_REQ_PHYS  0x{TSM_REQ:08X}u
#define TSM_META_PHYS 0x{TSM_META:08X}u
#define WP_GOLD_PHYS  0x{WP_GOLD:08X}u
#define REQ_STRIDE    {REQ_STRIDE}u
#define META_STRIDE   {META_STRIDE}u
#define WM_STRIDE     0x{WM_STRIDE:X}u
#define N_JOBS        207
#define N_FRAMES      35
""", newline='\n')
print('jobs', len(vec), 'planner frames', sum(1 for x in fmap if x), 'files', len(tsv) - 1)
