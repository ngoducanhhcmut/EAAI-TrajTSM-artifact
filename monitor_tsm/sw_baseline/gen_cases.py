"""Claude 04/11/2026: reference cases for the C port (tsmx_kernel.c) from the Python golden.
Writes cases.h: inputs + expected b4/b3/select results per case. usage: python gen_cases.py [n] [seed]
"""
import random, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'golden'))
from tsmx_golden import model as M

REASONS = ['ok', 'range', 'phase_alignment', 'horizon', 'trajectory', 'lane_range', 'numeric',
           'object_overflow', 'lane', 'object_range', 'object_speed_bound', 'time', 'separation']
S = M.S
MOD = 1 << 64

def row_cs(rows):
    cs = 0
    for r in rows:
        for f in r: cs = (cs * 1000003 + f) % MOD
    return cs

def s64(u): return u - MOD if u >= 1 << 63 else u

def rand_case(rng):
    x = rng.randint(-100, 100) * S + rng.randint(0, S)
    v = rng.choice([0, rng.randint(0, 10 * S), 10 * S, 9800000])
    a = rng.choice([0, -8 * S, 2 * S, rng.randint(-8 * S, 2 * S)])
    n = rng.choice([0, 1, 1, 2, 4, 8, 16, 32])
    objs = []
    for _ in range(n):
        if rng.random() < 0.7: ox = x + rng.randint(5, 150) * S
        else: ox = x - rng.randint(5, 80) * S
        objs.append(M.Motion(ox, rng.randint(0, 15 * S), rng.choice([0, rng.randint(-8 * S, 2 * S)]),
                             4800000 + rng.randint(0, 2 * S), rng.choice([0, rng.randint(0, 6000000)]),
                             rng.choice([0, -4 * S, rng.randint(-8 * S, 2 * S)])))
    return x, v, a, objs

def main():
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 120
    rng = random.Random(int(sys.argv[2]) if len(sys.argv) > 2 else 20261104)
    cases = []
    for _ in range(n):
        x, v, a, objs = rand_case(rng)
        b4, b3 = [], []
        for cid in range(16):
            tr = M.b4_mrmgen(x, v, a, cid)
            b4.append((int(tr.accept), len(tr.rows), tr.stop, s64(row_cs(tr.rows)), REASONS.index(tr.reason)))
            try:
                g = M.b3_geom(tr, tuple(objs))
                b3.append((int(g.accept), g.margin, REASONS.index(g.reason), g.steps))
            except ValueError as e:
                b3.append((0, -2, 99, -1))
        sel = M.select_world(M.Ego(0, x, v, a, 0, 0), tuple(objs), (-1800000, 1800000))[0]
        cases.append((x, v, a, objs, b4, b3, sel))
    L = ['/* generated by gen_cases.py (Python golden) - do not edit */', f'#define NCASES {n}',
         'static const int64_t CASE_EGO[NCASES][3] = {' + ','.join('{%dLL,%dLL,%dLL}' % c[:3] for c in cases) + '};',
         'static const int CASE_NOBJ[NCASES] = {' + ','.join(str(len(c[3])) for c in cases) + '};',
         'static const int64_t CASE_OBJ[NCASES][32][6] = {' + ','.join(
             '{' + ','.join('{%dLL,%dLL,%dLL,%dLL,%dLL,%dLL}' % (o.x, o.v, o.a, o.length, o.event, o.after_a)
                            for o in c[3]) + ('' if c[3] else '{0}') + '}' for c in cases) + '};',
         'static const int64_t CASE_B4[NCASES][16][5] = {' + ','.join(
             '{' + ','.join('{%dLL,%dLL,%dLL,%dLL,%dLL}' % t for t in c[4]) + '}' for c in cases) + '};',
         'static const int64_t CASE_B3[NCASES][16][4] = {' + ','.join(
             '{' + ','.join('{%dLL,%dLL,%dLL,%dLL}' % t for t in c[5]) + '}' for c in cases) + '};',
         'static const int CASE_SEL[NCASES] = {' + ','.join(str(c[6]) for c in cases) + '};']
    (HERE / 'cases.h').write_text('\n'.join(L) + '\n')
    acc = sum(c[6] != 15 for c in cases)
    print(f'wrote cases.h: {n} cases, select certified {acc}/{n}, objects total {sum(len(c[3]) for c in cases)}')

if __name__ == '__main__':
    main()
