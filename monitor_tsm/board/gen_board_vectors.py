"""Claude 04/11/2026: board replay data for the TSM-X ZCU106 test.

Inputs : tb/integ/<file>.mem (same vectors as the integration bench) and the board-equivalent
         stream-bench log (tb/board/vl_stream_r2/<run>.txt) for the per-job ACK sequence,
         the command-frame count and the simulated CSR cycle count.
Outputs: board/vectors/<tag>.tcl   - per-job reset/time/ack/seq + the 1399 rx words (xsdb data)
         board/vectors/<tag>.json  - expected response/command/event/CSR values per job
usage: python gen_board_vectors.py <file.mem> <stream_log.txt> <tag> [limit]
"""
import json, re, sys
from pathlib import Path
HW = Path(__file__).resolve().parents[1]
W = dict(reset=1, req=44673, rsp=38, cmd=1897, ing=332, sup=8, lost=32, event=1056)
ORDER = ['reset', 'req', 'rsp', 'cmd', 'ing', 'sup', 'lost', 'event']
VW = sum(W.values())

def fields(line):
    v = int(line, 16)
    out = {}; pos = VW
    for k in ORDER:
        pos -= W[k]; out[k] = (v >> pos) & ((1 << W[k]) - 1)
    return out

def rx_words(req):
    words = [1, 5585]
    for k in range(1396):
        w = (req >> (44672 - 32 * k - 31)) & 0xffffffff
        words.append(int.from_bytes(w.to_bytes(4, 'big'), 'little'))   # payload byte 0 -> bus bits 7:0
    words.append((req & 1) << 7)                                       # final word: keep=0001, bit 0 in bus bit 7
    return words

def cmd_words(cmd):
    b = (cmd << 7).to_bytes(238, 'big')                                # 1897 bits + 7 zero pad = 238 bytes
    words = [2, 238]
    for i in range(0, 240, 4):
        chunk = b[i:i + 4] + bytes(max(0, i + 4 - 238))
        words.append(int.from_bytes(chunk, 'little'))
    return words                                                       # 62 words, last keep=0011

def status(rsp, sup):
    s = 0
    s |= (rsp & 1) << 1
    s |= (1 if (not (rsp & 1)) or ((rsp >> 26) & 7) == 3 or ((rsp >> 9) & 1) else 0) << 2
    s |= ((rsp >> 26) & 7) << 3
    s |= ((sup >> 1) & 1) << 6
    s |= (sup & 1) << 7
    s |= (rsp & 1) << 8
    s |= ((rsp >> 10) & 3) << 16
    return s

def main():
    mem, log, tag = sys.argv[1], sys.argv[2], sys.argv[3]
    limit = int(sys.argv[4]) if len(sys.argv) > 4 else None
    lines = [l for l in (HW / 'tb' / 'integ' / mem).read_text().split() if l]
    text = Path(log).read_text(errors='replace')
    vec = {int(m[0]): (int(m[1]), int(m[2], 16), int(m[3]), int(m[4], 16))
           for m in re.findall(r'BOARDVEC job=(\d+) reset=(\d+) time=([0-9a-f]+) ack=(\d+) seq=([0-9a-f]+)', text)}
    cyc = {int(a): int(b) for a, b in re.findall(r'BOARDCYC job=(\d+) csr_cycles=(\d+)', text)}
    cmds = {}
    for a, b in re.findall(r'BOARDCMD job=(\d+) frames=(\d+)', text):
        cmds[int(a)] = cmds.get(int(a), 0) + 1
    n = len(vec) if limit is None else min(limit, len(vec))
    assert n > 0 and all(j in vec and j in cyc for j in range(n)), 'stream log incomplete'
    out = HW / 'board' / 'vectors'; out.mkdir(exist_ok=True)
    exp = []
    with open(out / f'{tag}.tcl', 'w', newline='\n') as t:
        t.write(f'# generated by gen_board_vectors.py from {mem} + {Path(log).name}\nset NJOBS {n}\n')
        for j in range(n):
            f = fields(lines[j]); r, tm, ack, seq = vec[j]
            assert r == f['reset'] and tm == f['req'] >> 44641 and ack == (f['req'] >> 33856) & 1, ('vector/log mismatch', j)
            t.write(f'set JOB({j}) {{{r} {tm} {ack} {seq}}}\n')
            t.write(f'set RX({j}) {{' + ' '.join('0x%08x' % w for w in rx_words(f['req'])) + '}\n')
            exp.append(dict(job=j, rsp='%010x' % f['rsp'], cmd_frames=cmds.get(j, 0),
                            cmd_words=['%08x' % w for w in cmd_words(f['cmd'])],
                            event='%0264x' % f['event'], reason=(f['rsp'] >> 29) & 0xff,
                            status='%08x' % status(f['rsp'], f['sup']), lost='%08x' % f['lost'],
                            sim_csr_cycles=cyc[j]))
    (out / f'{tag}.json').write_text(json.dumps(dict(source=mem, log=str(log), jobs=exp), indent=1))
    # {sim_csr_cycles[31:0], cmd_frames[7:0], seq[31:0]} per job for tb/board/tb_board_top.sv
    with open(out / f'{tag}_seq.mem', 'w', newline='\n') as m:
        for j in range(n):
            m.write('%08x%02x%08x\n' % (cyc[j], cmds.get(j, 0), vec[j][3]))
    print('wrote', out / f'{tag}.tcl', n, 'jobs')

if __name__ == '__main__':
    main()
